def build_project_pdf_reportlab(
    project: dict,
    risks: Optional[List[dict]] = None,
    allocations: Optional[List[dict]] = None,
    status_updates: Optional[List[dict]] = None
) -> bytes:
    """
    Build a professional, widescreen (16:9) project PDF report using ReportLab.
    
    This function is 100% crash-proof and will always return valid PDF bytes.
    
    Args:
        project: Project dictionary with keys like name, client_name, status, dates, etc.
        risks: Optional list of risk dictionaries
        allocations: Optional list of allocation dictionaries
        status_updates: Optional list of status update dictionaries
    
    Returns:
        bytes: PDF document as bytes
    """
    try:
        logger.info(f"Building ReportLab PDF for project: {project.get('name', 'Unknown')}")
        
        # Create buffer
        buffer = io.BytesIO()
        
        # Create document with widescreen dimensions
        doc = SimpleDocTemplate(
            buffer,
            pagesize=(WIDESCREEN_WIDTH, WIDESCREEN_HEIGHT),
            rightMargin=0.5 * inch,
            leftMargin=0.5 * inch,
            topMargin=0.5 * inch,
            bottomMargin=0.6 * inch,
            title=f"Project Report - {project.get('name', 'Untitled')}",
            author="DD Consulting"
        )
        
        # Initialize styles
        styles = create_styles()
        
        # Build document elements
        elements = []
        
        # 1. Header Banner
        elements.extend(build_header_banner(project, styles))
        
        # 2. Metrics Row
        elements.extend(build_metrics_row(project, styles))
        
        # 3. Executive Summary
        executive_summary = safe_str(
            project.get('executive_summary', ''),
            'No executive summary provided.'
        )
        summary_box = build_section_box("Executive Summary", executive_summary, styles)
        elements.append(summary_box)
        elements.append(Spacer(1, 0.15 * inch))
        
        # 4. Project Objective
        project_objective = safe_str(
            project.get('project_objective', ''),
            'No project objective defined.'
        )
        objective_box = build_section_box("Project Objective", project_objective, styles)
        elements.append(objective_box)
        elements.append(Spacer(1, 0.2 * inch))
        
        # 5. Team Allocations
        if allocations:
            elements.extend(build_allocations_table(allocations, styles))
        
        # 6. Active Risks
        if risks:
            elements.extend(build_risks_table(risks, styles))
        
        # 7. Status Update (Accomplishments & Next Steps)
        if status_updates:
            elements.extend(build_status_update_section(status_updates, styles))
        
        # Build the PDF
        doc.build(elements, canvasmaker=NumberedCanvas)
        
        # Get bytes
        pdf_bytes = buffer.getvalue()
        buffer.close()
        
        logger.info(f"Successfully generated PDF: {len(pdf_bytes)} bytes")
        return pdf_bytes
        
    except Exception as e:
        logger.error(f"Error generating ReportLab PDF: {str(e)}", exc_info=True)
        
        # Fallback: Return a minimal valid PDF
        try:
            buffer = io.BytesIO()
            doc = SimpleDocTemplate(
                buffer,
                pagesize=(WIDESCREEN_WIDTH, WIDESCREEN_HEIGHT),
                title="Error Report"
            )
            
            styles = getSampleStyleSheet()
            error_message = f"An error occurred while generating the PDF report: {str(e)}"
            elements = [
                Paragraph("PDF Generation Error", styles['Title']),
                Spacer(1, 0.3 * inch),
                Paragraph(error_message, styles['Normal'])
            ]
            
            doc.build(elements)
            pdf_bytes = buffer.getvalue()
            buffer.close()
            
            logger.info("Returned fallback error PDF")
            return pdf_bytes
            
        except Exception as fallback_error:
            logger.critical(f"Fallback PDF generation also failed: {str(fallback_error)}")
            # Return minimal valid PDF bytes as last resort
            return b'%PDF-1.4\n1 0 obj\n<< /Type /Catalog /Pages 2 0 R >>\nendobj\n2 0 obj\n<< /Type /Pages /Kids [3 0 R] /Count 1 >>\nendobj\n3 0 obj\n<< /Type /Page /Parent 2 0 R /Resources << /Font << /F1 << /Type /Font /Subtype /Type1 /BaseFont /Helvetica >> >> >> /MediaBox [0 0 960 540] /Contents 4 0 R >>\nendobj\n4 0 obj\n<< /Length 44 >>\nstream\nBT\n/F1 12 Tf\n50 500 Td\n(PDF Generation Error) Tj\nET\nendstream\nendobj\nxref\n0 5\n0000000000 65535 f\n0000000009 00000 n\n0000000058 00000 n\n0000000115 00000 n\n0000000317 00000 n\ntrailer\n<< /Size 5 /Root 1 0 R >>\nstartxref\n410\n%%EOF'
