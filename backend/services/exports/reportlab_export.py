def safe_str(value: Any, default: str = "N/A") -> str:
    """Safely convert any value to string, with fallback."""
    if value is None:
        return default
    if isinstance(value, (list, dict)):
        return str(value) if value else default
    return str(value)


def safe_date_format(date_value: Any, default: str = "N/A") -> str:
    """Safely format date values."""
    if not date_value:
        return default
    try:
        if isinstance(date_value, str):
            # Try parsing ISO format
            date_obj = datetime.fromisoformat(date_value.replace('Z', '+00:00'))
            return date_obj.strftime("%b %d, %Y")
        elif hasattr(date_value, 'strftime'):
            return date_value.strftime("%b %d, %Y")
        return str(date_value)
    except Exception:
        return str(date_value) if date_value else default


