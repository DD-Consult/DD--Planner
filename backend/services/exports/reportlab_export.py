class NumberedCanvas(canvas.Canvas):
    """Custom canvas for headers and footers on every page."""
    
    def __init__(self, *args, **kwargs):
        canvas.Canvas.__init__(self, *args, **kwargs)
        self._saved_page_states = []
    
    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()
    
    def save(self):
        """Add page info to each page (page x of y)"""
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_elements(num_pages)
            canvas.Canvas.showPage(self)
        canvas.Canvas.save(self)
    
    def draw_page_elements(self, page_count):
        """Draw header and footer on each page."""
        self.saveState()
        
        # Footer
        self.setFont('Helvetica', 8)
        self.setFillColor(DD_GRAY)
        footer_text = "Generated by DD Planner • Confidential"
        footer_y = 0.3 * inch
        self.drawCentredString(WIDESCREEN_WIDTH / 2.0, footer_y, footer_text)
        
        # Page number (right side)
        page_num = f"Page {self._pageNumber} of {page_count}"
        self.drawRightString(WIDESCREEN_WIDTH - 0.5 * inch, footer_y, page_num)
        
        self.restoreState()


